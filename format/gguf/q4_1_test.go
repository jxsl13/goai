func TestQ41WireGolden(t *testing.T) {
	values := make([]float32, blockElems)
	for i := range values {
		values[i] = float32(i % 16)
	}
	got, err := Quantize(tensor.FromFloat32(tensor.Shape{blockElems}, values), Q4_1)
	if err != nil {
		t.Fatal(err)
	}
	want := []byte{
		0x00, 0x3c, // d = 1
		0x00, 0x00, // m = 0
		0x00, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77,
		0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
	}
	if !bytes.Equal(got, want) {
		t.Fatalf("Q4_1 wire bytes = % x, want % x", got, want)
	}
	decoded, err := Dequantize(got, Q4_1, blockElems)
	if err != nil {
		t.Fatal(err)
	}
	for i, want := range values {
		if got := decoded.Storage().F32()[i]; got != want {
			t.Fatalf("decoded[%d] = %v, want %v", i, got, want)
		}
	}
}

