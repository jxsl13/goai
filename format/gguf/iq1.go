// iq1Grid is the decoded [2048][8]float32 codebook, built once at init.
var iq1Grid [2048][8]float32

func init() {
	if len(iq1GridHex) != 8192 {
		panic("gguf: iq1 grid hex length")
	}
	unhex := func(c byte) byte {
		if c > 0x40 {
			c += 9
		}
		return c & 0x0F
	}
	gridMap := [3]float32{-1, 0, 1}
	for e := range 2048 {
		//perfscan:ignore PS3040 IQ1 grid codebook decode in init, one-time
		for b := range 2 {
			hi := unhex(iq1GridHex[e*4+b*2])
			lo := unhex(iq1GridHex[e*4+b*2+1])
			packed := hi<<4 | lo
			for k := range 4 {
				iq1Grid[e][b*4+k] = gridMap[(packed>>(2*k))&0x3]
			}
		}
	}
}

// dequantIQ1_S decodes IQ1_S blocks into an F32 tensor of the given shape.
func dequantIQ1_S(shape tensor.Shape, data []byte) (*tensor.Tensor, error) {
	n := shape.Numel()
	if n%qkK != 0 {
		return nil, fmt.Errorf("gguf: IQ1_S numel %d not multiple of %d", n, qkK)
	}
	nb := n / qkK
	if len(data) != nb*iq1sBlockSize {
		return nil, fmt.Errorf("gguf: IQ1_S data %dB, want %d", len(data), nb*iq1sBlockSize)
	}
	out := tensor.New(tensor.F32, shape)
	dst := out.Storage().F32()
	for b := range nb {
		blk := data[b*iq1sBlockSize : (b+1)*iq1sBlockSize]
		d := f16ToF32(binary.LittleEndian.Uint16(blk[0:]))
		qs := blk[2:34]
		for g := range 8 { // one qh u16 → 32 elements (4 grid rows)
			qh := binary.LittleEndian.Uint16(blk[34+g*2:])
			dl := d * float32(2*(qh>>12&7)+1)
			delta := float32(iq1Delta)
			if qh&0x8000 != 0 {
				delta = -iq1Delta
			}
			for j := range 4 {
				u := uint16(qs[g*4+j]) | (qh>>(3*j)&7)<<8
				gridRow := &iq1Grid[u]
				base := b*qkK + g*32 + j*8
				y := dst[base : base+8]
				for k := range y {
					y[k] = dl * (gridRow[k] + delta)
				}
			}
		}
	}
	return out, nil
}

// dequantIQ1_M decodes IQ1_M blocks into an F32 tensor of the given shape.
func dequantIQ1_M(shape tensor.Shape, data []byte) (*tensor.Tensor, error) {
	n := shape.Numel()
	if n%qkK != 0 {
		return nil, fmt.Errorf("gguf: IQ1_M numel %d not multiple of %d", n, qkK)
	}
	nb := n / qkK
	if len(data) != nb*iq1mBlockSize {
		return nil, fmt.Errorf("gguf: IQ1_M data %dB, want %d", len(data), nb*iq1mBlockSize)
	}
	out := tensor.New(tensor.F32, shape)
	dst := out.Storage().F32()
	for b := range nb {
		blk := data[b*iq1mBlockSize : (b+1)*iq1mBlockSize]
		qs, qh, scales := blk[0:32], blk[32:48], blk[48:56]
		// the f16 super-scale lives in the top nibbles of the four scale words.
		var dbits uint16
		for i := range 4 {
			w := binary.LittleEndian.Uint16(scales[i*2:])
			dbits |= (w & 0xF000) >> (12 - 4*i)
		}
		d := f16ToF32(dbits)
		for i := range 32 { // one qs byte → one 8-wide grid row
			sw := binary.LittleEndian.Uint16(scales[(i/8)*2:])
			sc := sw >> (3 * (i / 2 % 4)) & 0x07
			dl := d * float32(2*sc+1)
			nib := qh[i/2] >> (4 * (i % 2))
			u := uint16(qs[i]) | uint16(nib&0x07)<<8
			delta := float32(iq1Delta)
			if nib&0x08 != 0 {
				delta = -iq1Delta
			}
			gridRow := &iq1Grid[u]
			base := b*qkK + i*8
			y := dst[base : base+8]
			for k := range y {
				y[k] = dl * (gridRow[k] + delta)
			}
		}
	}
	return out, nil
}
