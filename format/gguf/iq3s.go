var iq3sGridMap = [8]float32{1, 3, 5, 7, 9, 11, 13, 15}

// iq3sGrid is the decoded [512][4]float32 codebook, built once at init.
var iq3sGrid [512][4]float32

func init() {
	if len(iq3sGridHex) != 2048 {
		panic("gguf: iq3s grid hex length")
	}
	unhex := func(c byte) byte {
		if c > 0x40 {
			c += 9
		}
		return c & 0x0F
	}
	for e := range 512 {
		for b := range 2 {
			hi := unhex(iq3sGridHex[e*4+b*2])
			lo := unhex(iq3sGridHex[e*4+b*2+1])
			packed := hi<<4 | lo
			for k := range 2 {
				iq3sGrid[e][b*2+k] = iq3sGridMap[(packed>>(4*k))&0x7]
			}
		}
	}
}

// dequantIQ3_S decodes IQ3_S blocks into an F32 tensor of the given shape.
func dequantIQ3_S(shape tensor.Shape, data []byte) (*tensor.Tensor, error) {
	n := shape.Numel()
	if n%qkK != 0 {
		return nil, fmt.Errorf("gguf: IQ3_S numel %d not multiple of %d", n, qkK)
	}
	nb := n / qkK
	if len(data) != nb*iq3sBlockSize {
		return nil, fmt.Errorf("gguf: IQ3_S data %dB, want %d", len(data), nb*iq3sBlockSize)
	}
	out := tensor.New(tensor.F32, shape)
	dst := out.Storage().F32()
	for b := range nb {
		blk := data[b*iq3sBlockSize : (b+1)*iq3sBlockSize]
		d := f16ToF32(binary.LittleEndian.Uint16(blk[0:]))
		qs, qh, signs, scales := blk[2:66], blk[66:74], blk[74:106], blk[106:110]
		for g := range 8 { // 32 elements per scale nibble
			sc := scales[g/2] >> (4 * (g % 2)) & 0x0F
			db := d * (1 + 2*float32(sc))
			for j := range 4 { // 8 elements: two 4-wide grid rows
				i1, i2 := g*8+j*2, g*8+j*2+1
				u1 := uint16(qs[i1]) | uint16(qh[g]>>(j*2)&1)<<8
				u2 := uint16(qs[i2]) | uint16(qh[g]>>(j*2+1)&1)<<8
				r1, r2 := &iq3sGrid[u1], &iq3sGrid[u2]
				sg := signs[g*4+j]
				base := b*qkK + g*32 + j*8
				y := dst[base : base+8]
				for k := range 4 {
					// branchless negate — see iq2xxs.go (docs/perf-notes-lowlevel.md)
					sb1 := (uint32(sg>>k) & 1) << 31
					sb2 := (uint32(sg>>(k+4)) & 1) << 31
					y[k] = math.Float32frombits(math.Float32bits(db*r1[k]) ^ sb1)
					y[k+4] = math.Float32frombits(math.Float32bits(db*r2[k]) ^ sb2)
				}
			}
		}
	}
	return out, nil
}
