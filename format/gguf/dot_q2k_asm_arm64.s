//go:build arm64

#include "textflag.h"

// Convert sixteen unsigned q2 values in SRC to four f32 vectors and apply the
// exact dequant operation order step*q-offset. Widen both dequantized weights
// and activations before the multiply-accumulate so affine cancellation does
// not consume the task's 1e-4 scalar-relative error budget.
#define DOT_Q2(SRC, ACC0, ACC1, ACC2, ACC3) \
	VTBL V24.B16, [SRC.B16], V8.B16; \
	VTBL V25.B16, [SRC.B16], V9.B16; \
	VTBL V26.B16, [SRC.B16], V10.B16; \
	VTBL V27.B16, [SRC.B16], V11.B16; \
	WORD $0x6F28E508; /* UCVTF V8.4S, V8.4S, #24 */ \
	WORD $0x6F28E529; /* UCVTF V9.4S, V9.4S, #24 */ \
	WORD $0x6F28E54A; /* UCVTF V10.4S, V10.4S, #24 */ \
	WORD $0x6F28E56B; /* UCVTF V11.4S, V11.4S, #24 */ \
	WORD $0x6E34DD08; /* FMUL V8.4S, V8.4S, V20.4S */ \
	WORD $0x6E34DD29; /* FMUL V9.4S, V9.4S, V20.4S */ \
	WORD $0x6E34DD4A; /* FMUL V10.4S, V10.4S, V20.4S */ \
	WORD $0x6E34DD6B; /* FMUL V11.4S, V11.4S, V20.4S */ \
	WORD $0x4EB5D508; /* FSUB V8.4S, V8.4S, V21.4S */ \
	WORD $0x4EB5D529; /* FSUB V9.4S, V9.4S, V21.4S */ \
	WORD $0x4EB5D54A; /* FSUB V10.4S, V10.4S, V21.4S */ \
	WORD $0x4EB5D56B; /* FSUB V11.4S, V11.4S, V21.4S */ \
	VLD1 (R4), [V12.S4, V13.S4, V14.S4, V15.S4]; \
	WORD $0x0E617904; /* FCVTL  V4.2D, V8.2S */ \
	WORD $0x4E617905; /* FCVTL2 V5.2D, V8.4S */ \
	WORD $0x0E617986; /* FCVTL  V6.2D, V12.2S */ \
	WORD $0x4E617987; /* FCVTL2 V7.2D, V12.4S */ \
	VFMLA V4.D2, V6.D2, ACC0.D2; \
	VFMLA V5.D2, V7.D2, ACC1.D2; \
	WORD $0x0E617924; /* FCVTL  V4.2D, V9.2S */ \
	WORD $0x4E617925; /* FCVTL2 V5.2D, V9.4S */ \
	WORD $0x0E6179A6; /* FCVTL  V6.2D, V13.2S */ \
	WORD $0x4E6179A7; /* FCVTL2 V7.2D, V13.4S */ \
	VFMLA V4.D2, V6.D2, ACC2.D2; \
	VFMLA V5.D2, V7.D2, ACC3.D2; \
	WORD $0x0E617944; /* FCVTL  V4.2D, V10.2S */ \
	WORD $0x4E617945; /* FCVTL2 V5.2D, V10.4S */ \
	WORD $0x0E6179C6; /* FCVTL  V6.2D, V14.2S */ \
	WORD $0x4E6179C7; /* FCVTL2 V7.2D, V14.4S */ \
	VFMLA V4.D2, V6.D2, ACC0.D2; \
	VFMLA V5.D2, V7.D2, ACC1.D2; \
	WORD $0x0E617964; /* FCVTL  V4.2D, V11.2S */ \
	WORD $0x4E617965; /* FCVTL2 V5.2D, V11.4S */ \
	WORD $0x0E6179E6; /* FCVTL  V6.2D, V15.2S */ \
	WORD $0x4E6179E7; /* FCVTL2 V7.2D, V15.4S */ \
	VFMLA V4.D2, V6.D2, ACC2.D2; \
	VFMLA V5.D2, V7.D2, ACC3.D2

// func dotQ2KBlockNeon(x *float32, qs *byte, coeff *float32, indexes *byte) float64
TEXT ·dotQ2KBlockNeon(SB), NOSPLIT, $0-40
	MOVD x+0(FP), R0
	MOVD qs+8(FP), R1
	MOVD coeff+16(FP), R2
	MOVD indexes+24(FP), R3

	VLD1 (R3), [V24.B16, V25.B16, V26.B16, V27.B16]
	VMOVI $0x03, V22.B16
	VEOR V16.B16, V16.B16, V16.B16
	VEOR V17.B16, V17.B16, V17.B16
	VEOR V18.B16, V18.B16, V18.B16
	VEOR V19.B16, V19.B16, V19.B16
	VEOR V28.B16, V28.B16, V28.B16
	VEOR V29.B16, V29.B16, V29.B16
	VEOR V30.B16, V30.B16, V30.B16
	VEOR V31.B16, V31.B16, V31.B16
	MOVD $2, R7

quant_half:
	VLD1 (R1), [V0.B16, V1.B16]
	ADD $32, R1, R1
	MOVD $4, R8

subblocks:
	VAND V22.B16, V0.B16, V2.B16
	VAND V22.B16, V1.B16, V3.B16
	VUSHR $2, V0.B16, V0.B16
	VUSHR $2, V1.B16, V1.B16

	VLD1R.P 4(R2), [V20.S4]
	VLD1R.P 4(R2), [V21.S4]
	MOVD R0, R4
	DOT_Q2(V2, V28, V29, V30, V31)
	VLD1R.P 4(R2), [V20.S4]
	VLD1R.P 4(R2), [V21.S4]
	ADD $64, R0, R4
	DOT_Q2(V3, V16, V17, V18, V19)
	ADD $128, R0, R0

	SUBS $1, R8, R8
	BNE subblocks
	SUBS $1, R7, R7
	BNE quant_half

	WORD $0x4E70D79C // FADD V28.2D, V28.2D, V16.2D
	WORD $0x4E71D7BD // FADD V29.2D, V29.2D, V17.2D
	WORD $0x4E72D7DE // FADD V30.2D, V30.2D, V18.2D
	WORD $0x4E73D7FF // FADD V31.2D, V31.2D, V19.2D
	WORD $0x4E7DD79C // FADD V28.2D, V28.2D, V29.2D
	WORD $0x4E7ED79C // FADD V28.2D, V28.2D, V30.2D
	WORD $0x4E7FD79C // FADD V28.2D, V28.2D, V31.2D
	WORD $0x7E70DB9C // FADDP V28.2D, F28
	FMOVD F28, ret+32(FP)
	RET
