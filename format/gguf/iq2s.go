// iq2sGrid is the decoded [1024][8]float32 codebook, built once at init.
var iq2sGrid [1024][8]float32

func init() {
	if len(iq2sGridHex) != 4096 {
		panic("gguf: iq2s grid hex length")
	}
	unhex := func(c byte) byte {
		if c > 0x40 {
			c += 9
		}
		return c & 0x0F
	}
	gridMap := [3]float32{0x08, 0x19, 0x2b}
	for e := range 1024 {
		//perfscan:ignore PS3040 IQ2_S grid decode in init, one-time
		for b := range 2 {
			hi := unhex(iq2sGridHex[e*4+b*2])
			lo := unhex(iq2sGridHex[e*4+b*2+1])
			packed := hi<<4 | lo
			for k := range 4 {
				iq2sGrid[e][b*4+k] = gridMap[(packed>>(2*k))&0x3]
			}
		}
	}
}

// dequantIQ2_S decodes IQ2_S blocks into an F32 tensor of the given shape.
func dequantIQ2_S(shape tensor.Shape, data []byte) (*tensor.Tensor, error) {
	n := shape.Numel()
	if n%qkK != 0 {
		return nil, fmt.Errorf("gguf: IQ2_S numel %d not multiple of %d", n, qkK)
	}
	nb := n / qkK
	if len(data) != nb*iq2sBlockSize {
		return nil, fmt.Errorf("gguf: IQ2_S data %dB, want %d", len(data), nb*iq2sBlockSize)
	}
	out := tensor.New(tensor.F32, shape)
	dst := out.Storage().F32()
	for b := range nb {
		blk := data[b*iq2sBlockSize : (b+1)*iq2sBlockSize]
		d := f16ToF32(binary.LittleEndian.Uint16(blk[0:]))
		qs, signs, qh, scales := blk[2:34], blk[34:66], blk[66:74], blk[74:82]
		for i := range 32 { // one qs byte → one 8-wide grid row
			sc := scales[i/4] >> (4 * (i / 2 % 2)) & 0x0F
			db := d * (0.5 + float32(sc)) * 0.25
			u := uint16(qs[i]) | uint16(qh[i/4]>>(2*(i%4))&0x3)<<8
			gridRow := &iq2sGrid[u]
			sg := signs[i]
			base := b*qkK + i*8
			y := dst[base : base+8]
			for k := range y {
				// branchless negate — see iq2xxs.go (docs/perf-notes-lowlevel.md)
				sbit := (uint32(sg>>k) & 1) << 31
				y[k] = math.Float32frombits(math.Float32bits(db*gridRow[k]) ^ sbit)
			}
		}
	}
	return out, nil
}
