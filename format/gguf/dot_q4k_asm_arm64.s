// Convert sixteen unsigned q4 nibbles in SRC to four f32 vectors, apply the
// exact dequant operation order step*q-offset, load sixteen activations, and
// accumulate four independent vectors. Keeping four accumulators breaks the
// single-FMLA dependency chain without changing element mapping.
#define DOT_Q4(SRC) \
	VTBL V24.B16, [SRC.B16], V8.B16; \
	VTBL V25.B16, [SRC.B16], V9.B16; \
	VTBL V26.B16, [SRC.B16], V10.B16; \
	VTBL V27.B16, [SRC.B16], V11.B16; \
	WORD $0x6F28E508; /* UCVTF V8.4S, V8.4S, #24 */ \
	WORD $0x6F28E529; /* UCVTF V9.4S, V9.4S, #24 */ \
	WORD $0x6F28E54A; /* UCVTF V10.4S, V10.4S, #24 */ \
	WORD $0x6F28E56B; /* UCVTF V11.4S, V11.4S, #24 */ \
	WORD $0x6E34DD08; /* FMUL V8.4S, V8.4S, V20.4S */ \
	WORD $0x6E34DD29; /* FMUL V9.4S, V9.4S, V20.4S */ \
	WORD $0x6E34DD4A; /* FMUL V10.4S, V10.4S, V20.4S */ \
	WORD $0x6E34DD6B; /* FMUL V11.4S, V11.4S, V20.4S */ \
	WORD $0x4EB5D508; /* FSUB V8.4S, V8.4S, V21.4S */ \
	WORD $0x4EB5D529; /* FSUB V9.4S, V9.4S, V21.4S */ \
	WORD $0x4EB5D54A; /* FSUB V10.4S, V10.4S, V21.4S */ \
	WORD $0x4EB5D56B; /* FSUB V11.4S, V11.4S, V21.4S */ \
	VLD1 (R4), [V12.S4, V13.S4, V14.S4, V15.S4]; \
	VFMLA V8.S4, V12.S4, V16.S4; \
	VFMLA V9.S4, V13.S4, V17.S4; \
	VFMLA V10.S4, V14.S4, V18.S4; \
	VFMLA V11.S4, V15.S4, V19.S4

// func dotQ4KBlockNeon(x *float32, qs *byte, coeff *float32, indexes *byte) float32
TEXT ·dotQ4KBlockNeon(SB), NOSPLIT, $0-36
	MOVD x+0(FP), R0
	MOVD qs+8(FP), R1
	MOVD coeff+16(FP), R2
	MOVD indexes+24(FP), R3

	VLD1 (R3), [V24.B16, V25.B16, V26.B16, V27.B16]
	VMOVI $0x0f, V23.B16
	VEOR V16.B16, V16.B16, V16.B16
	VEOR V17.B16, V17.B16, V17.B16
	VEOR V18.B16, V18.B16, V18.B16
	VEOR V19.B16, V19.B16, V19.B16
	MOVD $4, R7

pair:
	VLD1 (R1), [V0.B16, V1.B16]
	ADD $32, R1, R1
	VAND V23.B16, V0.B16, V2.B16
	VAND V23.B16, V1.B16, V3.B16
	VUSHR $4, V0.B16, V4.B16
	VUSHR $4, V1.B16, V5.B16

	VLD1R.P 4(R2), [V20.S4]
	VLD1R.P 4(R2), [V21.S4]
	MOVD R0, R4
	DOT_Q4(V2)
	ADD $64, R0, R4
	DOT_Q4(V3)

	VLD1R.P 4(R2), [V20.S4]
	VLD1R.P 4(R2), [V21.S4]
	ADD $128, R0, R4
	DOT_Q4(V4)
	ADD $192, R0, R4
	DOT_Q4(V5)

	ADD $256, R0, R0
	SUBS $1, R7, R7
	BNE pair

	WORD $0x4E31D610 // FADD V16.4S, V16.4S, V17.4S
	WORD $0x4E33D652 // FADD V18.4S, V18.4S, V19.4S
	WORD $0x4E32D610 // FADD V16.4S, V16.4S, V18.4S
	WORD $0x6E30D610 // FADDP V16.4S, V16.4S, V16.4S
	WORD $0x6E30D610 // FADDP V16.4S, V16.4S, V16.4S
	FMOVS F16, ret+32(FP)
	RET

// The dual-output kernel keeps the first result in V16..V19 and the second in
// V28..V31. V12..V15 holds each activation vector while both dequantized
// weight vectors consume it, halving activation loads versus two calls above.
#define DEQUANT_Q4_0(SRC) \
	VTBL V24.B16, [SRC.B16], V8.B16; \
	VTBL V25.B16, [SRC.B16], V9.B16; \
	VTBL V26.B16, [SRC.B16], V10.B16; \
	VTBL V27.B16, [SRC.B16], V11.B16; \
	WORD $0x6F28E508; \
	WORD $0x6F28E529; \
	WORD $0x6F28E54A; \
	WORD $0x6F28E56B; \
	WORD $0x6E34DD08; \
	WORD $0x6E34DD29; \
	WORD $0x6E34DD4A; \
	WORD $0x6E34DD6B; \
	WORD $0x4EB5D508; \
	WORD $0x4EB5D529; \
	WORD $0x4EB5D54A; \
	WORD $0x4EB5D56B

#define DEQUANT_Q4_1(SRC) \
	VTBL V24.B16, [SRC.B16], V8.B16; \
	VTBL V25.B16, [SRC.B16], V9.B16; \
	VTBL V26.B16, [SRC.B16], V10.B16; \
	VTBL V27.B16, [SRC.B16], V11.B16; \
	WORD $0x6F28E508; \
	WORD $0x6F28E529; \
	WORD $0x6F28E54A; \
	WORD $0x6F28E56B; \
	WORD $0x6E36DD08; /* FMUL V8.4S, V8.4S, V22.4S */ \
	WORD $0x6E36DD29; \
	WORD $0x6E36DD4A; \
	WORD $0x6E36DD6B; \
	WORD $0x4EB7D508; /* FSUB V8.4S, V8.4S, V23.4S */ \
	WORD $0x4EB7D529; \
	WORD $0x4EB7D54A; \
	WORD $0x4EB7D56B

#define ACCUM_Q4_0 \
	VFMLA V8.S4, V12.S4, V16.S4; \
	VFMLA V9.S4, V13.S4, V17.S4; \
	VFMLA V10.S4, V14.S4, V18.S4; \
	VFMLA V11.S4, V15.S4, V19.S4

#define ACCUM_Q4_1 \
	VFMLA V8.S4, V12.S4, V28.S4; \
	VFMLA V9.S4, V13.S4, V29.S4; \
	VFMLA V10.S4, V14.S4, V30.S4; \
	VFMLA V11.S4, V15.S4, V31.S4

#define MUL_Q4K_COEFF_V20 \
	WORD $0x6E34DD08; /* FMUL V8.4S, V8.4S, V20.4S */ \
	WORD $0x6E34DD29; \
	WORD $0x6E34DD4A; \
	WORD $0x6E34DD6B

#define MUL_Q4K_COEFF_V22 \
	WORD $0x6E36DD08; /* FMUL V8.4S, V8.4S, V22.4S */ \
	WORD $0x6E36DD29; \
	WORD $0x6E36DD4A; \
	WORD $0x6E36DD6B

// Decode all eight Q4_K scale/min pairs for one row. Its multiply macro uses
// alternating exact f16-table d/dmin lanes, so the vector result is bit-identical
// to the scalar coefficient builder while amortizing extraction and conversion.
#define BUILD_Q4K_COEFF_VECTOR(SPTR, MUL, DST) \
	ADD $4, SPTR, R6; \
	VLD1 (R6), [V0.B16]; \
	VTBL V18.B16, [V0.B16], V1.B16; \
	VAND V16.B16, V1.B16, V6.B16; \
	VUSHR $6, V1.B16, V1.B16; \
	VSHL $4, V1.B16, V1.B16; \
	VTBL V19.B16, [V0.B16], V2.B16; \
	WORD $0x6E314442; /* VUSHL V17.B16, V2.B16, V2.B16 */ \
	VAND V21.B16, V2.B16, V2.B16; \
	VORR V1.B16, V2.B16, V2.B16; \
	VEXT $8, V2.B16, V6.B16, V11.B16; \
	VTBL V24.B16, [V11.B16], V8.B16; \
	VTBL V25.B16, [V11.B16], V9.B16; \
	VTBL V26.B16, [V11.B16], V10.B16; \
	VTBL V27.B16, [V11.B16], V11.B16; \
	WORD $0x6F28E508; /* UCVTF V8.4S, V8.4S, #0 */ \
	WORD $0x6F28E529; \
	WORD $0x6F28E54A; \
	WORD $0x6F28E56B; \
	MUL; \
	VST1 [V8.S4, V9.S4, V10.S4, V11.S4], (DST)

// func dotQ4KPairBlockNeon(x *float32, qs0, qs1 *byte, coeff0, coeff1 *float32, indexes *byte) (out0, out1 float32)
TEXT ·dotQ4KPairBlockNeon(SB), NOSPLIT, $0-56
	MOVD x+0(FP), R0
	MOVD qs0+8(FP), R1
	MOVD qs1+16(FP), R2
	MOVD coeff0+24(FP), R3
	MOVD coeff1+32(FP), R4
	MOVD indexes+40(FP), R5

	VLD1 (R5), [V24.B16, V25.B16, V26.B16, V27.B16]
	VEOR V16.B16, V16.B16, V16.B16
	VEOR V17.B16, V17.B16, V17.B16
	VEOR V18.B16, V18.B16, V18.B16
	VEOR V19.B16, V19.B16, V19.B16
	VEOR V28.B16, V28.B16, V28.B16
	VEOR V29.B16, V29.B16, V29.B16
	VEOR V30.B16, V30.B16, V30.B16
	VEOR V31.B16, V31.B16, V31.B16
	MOVD $4, R8

pair_dual:
	VLD1 (R1), [V0.B16, V1.B16]
	ADD $32, R1, R1
	VLD1 (R2), [V6.B16, V7.B16]
	ADD $32, R2, R2
	VMOVI $0x0f, V23.B16
	VAND V23.B16, V0.B16, V2.B16
	VAND V23.B16, V1.B16, V3.B16
	VUSHR $4, V0.B16, V4.B16
	VUSHR $4, V1.B16, V5.B16
	VAND V23.B16, V6.B16, V0.B16
	VAND V23.B16, V7.B16, V1.B16
	VUSHR $4, V6.B16, V6.B16
	VUSHR $4, V7.B16, V7.B16

	VLD1R.P 4(R3), [V20.S4]
	VLD1R.P 4(R3), [V21.S4]
	VLD1R.P 4(R4), [V22.S4]
	VLD1R.P 4(R4), [V23.S4]
	MOVD R0, R7
	DEQUANT_Q4_0(V2)
	VLD1 (R7), [V12.S4, V13.S4, V14.S4, V15.S4]
	ACCUM_Q4_0
	DEQUANT_Q4_1(V0)
	ACCUM_Q4_1
	ADD $64, R7, R7
	DEQUANT_Q4_0(V3)
	VLD1 (R7), [V12.S4, V13.S4, V14.S4, V15.S4]
	ACCUM_Q4_0
	DEQUANT_Q4_1(V1)
	ACCUM_Q4_1

	VLD1R.P 4(R3), [V20.S4]
	VLD1R.P 4(R3), [V21.S4]
	VLD1R.P 4(R4), [V22.S4]
	VLD1R.P 4(R4), [V23.S4]
	ADD $64, R7, R7
	DEQUANT_Q4_0(V4)
	VLD1 (R7), [V12.S4, V13.S4, V14.S4, V15.S4]
	ACCUM_Q4_0
	DEQUANT_Q4_1(V6)
	ACCUM_Q4_1
	ADD $64, R7, R7
	DEQUANT_Q4_0(V5)
	VLD1 (R7), [V12.S4, V13.S4, V14.S4, V15.S4]
	ACCUM_Q4_0
	DEQUANT_Q4_1(V7)
	ACCUM_Q4_1

	ADD $256, R0, R0
	SUBS $1, R8, R8
	BNE pair_dual

	WORD $0x4E31D610 // FADD V16.4S, V16.4S, V17.4S
	WORD $0x4E33D652 // FADD V18.4S, V18.4S, V19.4S
	WORD $0x4E32D610 // FADD V16.4S, V16.4S, V18.4S
	WORD $0x6E30D610 // FADDP V16.4S, V16.4S, V16.4S
	WORD $0x6E30D610 // FADDP V16.4S, V16.4S, V16.4S
	WORD $0x4E3DD79C // FADD V28.4S, V28.4S, V29.4S
	WORD $0x4E3FD7DE // FADD V30.4S, V30.4S, V31.4S
	WORD $0x4E3ED79C // FADD V28.4S, V28.4S, V30.4S
	WORD $0x6E3CD79C // FADDP V28.4S, V28.4S, V28.4S
	WORD $0x6E3CD79C // FADDP V28.4S, V28.4S, V28.4S
	FMOVS F16, out0+48(FP)
	FMOVS F28, out1+52(FP)
	RET

// func dotQ4KPairRowNeon(x *float32, raw0, raw1 *byte, f16 *float32, indexes *byte, blocks int) (out0, out1 float64)
TEXT ·dotQ4KPairRowNeon(SB), NOSPLIT, $144-64
	MOVD x+0(FP), R0
	MOVD raw0+8(FP), R1
	MOVD raw1+16(FP), R2
	MOVD f16+24(FP), R3
	MOVD indexes+32(FP), R4
	MOVD blocks+40(FP), R5

	VLD1 (R4), [V24.B16, V25.B16, V26.B16, V27.B16]
	MOVD ZR, 128(RSP)
	MOVD ZR, 136(RSP)

pair_row_block:
	MOVHU (R1), R6
	FMOVS (R3)(R6<<2), F20
	MOVHU 2(R1), R6
	FMOVS (R3)(R6<<2), F21
	MOVHU (R2), R6
	FMOVS (R3)(R6<<2), F22
	MOVHU 2(R2), R6
	FMOVS (R3)(R6<<2), F23

	VDUP V20.S[0], V20.S4
	VDUP V21.S[0], V21.S4
	VZIP1 V21.S4, V20.S4, V20.S4
	VDUP V22.S[0], V22.S4
	VDUP V23.S[0], V23.S4
	VZIP1 V23.S4, V22.S4, V22.S4
	VMOVI $0x3f, V16.B16
	VMOVI $0x0f, V21.B16
	ADD $64, R4, R6
	VLD1 (R6), [V17.B16, V18.B16, V19.B16]
	MOVD RSP, R13
	ADD $64, RSP, R14
	BUILD_Q4K_COEFF_VECTOR(R1, MUL_Q4K_COEFF_V20, R13)
	BUILD_Q4K_COEFF_VECTOR(R2, MUL_Q4K_COEFF_V22, R14)

	ADD $16, R1, R11
	ADD $16, R2, R12
	VEOR V16.B16, V16.B16, V16.B16
	VEOR V17.B16, V17.B16, V17.B16
	VEOR V18.B16, V18.B16, V18.B16
	VEOR V19.B16, V19.B16, V19.B16
	VEOR V28.B16, V28.B16, V28.B16
	VEOR V29.B16, V29.B16, V29.B16
	VEOR V30.B16, V30.B16, V30.B16
	VEOR V31.B16, V31.B16, V31.B16
	MOVD $4, R15

pair_row_dual:
	VLD1 (R11), [V0.B16, V1.B16]
	ADD $32, R11, R11
	VLD1 (R12), [V6.B16, V7.B16]
	ADD $32, R12, R12
	VMOVI $0x0f, V23.B16
	VAND V23.B16, V0.B16, V2.B16
	VAND V23.B16, V1.B16, V3.B16
	VUSHR $4, V0.B16, V4.B16
	VUSHR $4, V1.B16, V5.B16
	VAND V23.B16, V6.B16, V0.B16
	VAND V23.B16, V7.B16, V1.B16
	VUSHR $4, V6.B16, V6.B16
	VUSHR $4, V7.B16, V7.B16

	VLD1R.P 4(R13), [V20.S4]
	VLD1R.P 4(R13), [V21.S4]
	VLD1R.P 4(R14), [V22.S4]
	VLD1R.P 4(R14), [V23.S4]
	MOVD R0, R7
	DEQUANT_Q4_0(V2)
	VLD1 (R7), [V12.S4, V13.S4, V14.S4, V15.S4]
	ACCUM_Q4_0
	DEQUANT_Q4_1(V0)
	ACCUM_Q4_1
	ADD $64, R7, R7
	DEQUANT_Q4_0(V3)
	VLD1 (R7), [V12.S4, V13.S4, V14.S4, V15.S4]
	ACCUM_Q4_0
	DEQUANT_Q4_1(V1)
	ACCUM_Q4_1

	VLD1R.P 4(R13), [V20.S4]
	VLD1R.P 4(R13), [V21.S4]
	VLD1R.P 4(R14), [V22.S4]
	VLD1R.P 4(R14), [V23.S4]
	ADD $64, R7, R7
	DEQUANT_Q4_0(V4)
	VLD1 (R7), [V12.S4, V13.S4, V14.S4, V15.S4]
	ACCUM_Q4_0
	DEQUANT_Q4_1(V6)
	ACCUM_Q4_1
	ADD $64, R7, R7
	DEQUANT_Q4_0(V5)
	VLD1 (R7), [V12.S4, V13.S4, V14.S4, V15.S4]
	ACCUM_Q4_0
	DEQUANT_Q4_1(V7)
	ACCUM_Q4_1

	ADD $256, R0, R0
	SUBS $1, R15, R15
	BNE pair_row_dual

	WORD $0x4E31D610 // FADD V16.4S, V16.4S, V17.4S
	WORD $0x4E33D652 // FADD V18.4S, V18.4S, V19.4S
	WORD $0x4E32D610 // FADD V16.4S, V16.4S, V18.4S
	WORD $0x6E30D610 // FADDP V16.4S, V16.4S, V16.4S
	WORD $0x6E30D610 // FADDP V16.4S, V16.4S, V16.4S
	WORD $0x4E3DD79C // FADD V28.4S, V28.4S, V29.4S
	WORD $0x4E3FD7DE // FADD V30.4S, V30.4S, V31.4S
	WORD $0x4E3ED79C // FADD V28.4S, V28.4S, V30.4S
	WORD $0x6E3CD79C // FADDP V28.4S, V28.4S, V28.4S
	WORD $0x6E3CD79C // FADDP V28.4S, V28.4S, V28.4S
	FCVTSD F16, F4
	FMOVD 128(RSP), F5
	FADDD F4, F5
	FMOVD F5, 128(RSP)
	FCVTSD F28, F4
	FMOVD 136(RSP), F5
	FADDD F4, F5
	FMOVD F5, 136(RSP)

	ADD $144, R1, R1
	ADD $144, R2, R2
	SUBS $1, R5, R5
	BNE pair_row_block

	FMOVD 128(RSP), F0
	FMOVD 136(RSP), F1
	FMOVD F0, out0+48(FP)
	FMOVD F1, out1+56(FP)
	RET
